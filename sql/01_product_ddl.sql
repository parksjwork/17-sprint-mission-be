-- 상품 테이블
CREATE TABLE product (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name        VARCHAR(10)    NOT NULL,
    price       INTEGER        NOT NULL,
    description TEXT           NOT NULL,
    created_at  TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),

    CONSTRAINT product_pkey PRIMARY KEY (id),
    CONSTRAINT product_price_check CHECK (price >= 0)
);

-- 상품 댓글 테이블
CREATE TABLE product_comment (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    product_id INTEGER        NOT NULL,
    content    TEXT           NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),

    CONSTRAINT product_comment_pkey PRIMARY KEY (id),
    CONSTRAINT product_comment_product_id_fkey
        FOREIGN KEY (product_id)
        REFERENCES product (id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- 태그 테이블
CREATE TABLE tag (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name       VARCHAR(5)     NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),

    CONSTRAINT tag_pkey PRIMARY KEY (id),
    CONSTRAINT tag_name_key UNIQUE (name)
);

-- 상품과 태그의 중간 테이블
CREATE TABLE product_to_tag (
    product_id INTEGER NOT NULL,
    tag_id     INTEGER NOT NULL,

    CONSTRAINT product_to_tag_pkey
        PRIMARY KEY (product_id, tag_id),

    CONSTRAINT product_to_tag_product_id_fkey
        FOREIGN KEY (product_id)
        REFERENCES product (id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,

    CONSTRAINT product_to_tag_tag_id_fkey
        FOREIGN KEY (tag_id)
        REFERENCES tag (id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- 인덱스
CREATE INDEX product_created_at_idx
    ON product (created_at);

CREATE INDEX product_comment_product_id_id_idx
    ON product_comment (product_id, id);

CREATE INDEX product_to_tag_tag_id_idx
    ON product_to_tag (tag_id);