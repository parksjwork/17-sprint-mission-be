-- 게시글 테이블
CREATE TABLE article (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    title      VARCHAR(200)   NOT NULL,
    content    TEXT           NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),

    CONSTRAINT article_pkey PRIMARY KEY (id)
);

-- 게시글 댓글 테이블
CREATE TABLE article_comment (
    id         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    article_id INTEGER        NOT NULL,
    content    TEXT           NOT NULL,
    created_at TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT NOW(),

    CONSTRAINT article_comment_pkey PRIMARY KEY (id),
    CONSTRAINT article_comment_article_id_fkey
        FOREIGN KEY (article_id)
        REFERENCES article (id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

-- 인덱스
CREATE INDEX article_created_at_idx
    ON article (created_at);

CREATE INDEX article_comment_article_id_id_idx
    ON article_comment (article_id, id);